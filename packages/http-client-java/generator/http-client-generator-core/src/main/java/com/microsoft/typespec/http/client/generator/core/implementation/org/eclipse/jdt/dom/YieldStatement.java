package com.microsoft.typespec.http.client.generator.core.implementation.org.eclipse.jdt.dom;

/**
 * Yield statement AST node type.
 *
 * <pre>
 * YieldStatement:
 *		<b>Yield</b> <b>{ Identifier/Expression }</b>
 * </pre>
 *
 * @since 3.22
 */
public class YieldStatement extends Statement {

    /**
     * The "expression" structural property of this node type (child type: {@link Expression}). (added in JEP 354).
     */
    public static final ChildPropertyDescriptor EXPRESSION_PROPERTY
        = new ChildPropertyDescriptor(Expression.class, false);

    /**
     * <code>true</code> indicates implicit and <code>false</code> indicates not implicit.
     */
    private boolean isImplicit = false;

    /**
     * The expression
     */
    private Expression expression = null;

    /**
     * Creates a new unparented Yield statement node owned by the given AST. By default, the Yield statement has
     * identifier/expression. <p> N.B. This constructor is package-private. </p>
     *
     * @param ast the AST that is to own this node
     */
    YieldStatement(AST ast) {
        super(ast);

    }

    @Override
    final int getNodeType0() {
        return 101;
    }

    @Override
    void accept0(ASTVisitor visitor) {
        boolean visitChildren = visitor.visit(this);
        if (visitChildren) {
            acceptChild(visitor, getExpression());
        }

    }

    /**
     * Returns the expression of this Yield statement, or <code>null</code> if there is none.
     *
     * @return the expression, or <code>null</code> if there is none
     * @since 3.22
     */
    public Expression getExpression() {

        return this.expression;
    }

    /**
     * Sets or clears the expression of this Yield statement.
     *
     * @param expression the expression
     * @exception IllegalArgumentException if: <ul> <li>the node belongs to a different AST</li> <li>the node already
     * has a parent</li> </ul>
     * @since 3.22
     */
    public void setExpression(Expression expression) {

        ASTNode oldChild = this.expression;
        preReplaceChild(oldChild, expression, EXPRESSION_PROPERTY);
        this.expression = expression;

    }

    /**
     * Gets the isImplicit of this break statement as <code>true</code> or <code>false</code>. <code>true</code>
     * indicates implicit and <code>false</code> indicates not implicit.
     *
     * @return isImplicit <code>true</code> or <code>false</code>
     * @since 3.22
     */
    public boolean isImplicit() {

        return this.isImplicit;
    }

    /**
     * Sets the isImplicit of this break statement as <code>true</code> or <code>false</code>. <code>true</code>
     * indicates implicit and <code>false</code> indicates not implicit. This flag is generated by compiler and is not
     * expected to be set by client.
     *
     * @param isImplicit <code>true</code> or <code>false</code>
     */
    void setImplicit(boolean isImplicit) {

        this.isImplicit = isImplicit;
    }
}
