namespace Microsoft.TypeSpec.Generator.Tests.Writers
{
    internal partial class PreparedFieldTypeTests
    {
        // Mechanical channel-metadata transfer, not production body permission.
        // The real reference field is this fixture's subject, not a dummy granting
        // body permission. The opaque callback hand-calls an output-only API; it
        // supplies NO admitted body occurrence, binding fact, or consumer license.
        [TestCase(false)]
        [TestCase(true)]
        public void StandardWriterTransfersRealFieldAndTestOnlyBodyAlternativesWithoutReplay(bool independentNamespaceUse)
        {
            var previous = CodeModelGenerator.Instance;
            // Reuse the counting service's DEFAULT TypeFactory and base.GetWriter.
            // Legacy internal Create below does not require public pipeline admission.
            var services = new GeneratedInstanceWriterService(new GeneratorContext(previous.Configuration))
            { SourceInputModel = previous.SourceInputModel };
            CodeModelGenerator.Instance = services;
            try
            {
                const string externalName = "PreparedNameTransferWidget";
                var inputs = ReferenceCompilation(CreateExternalWidget(externalName));
                var externalIdentity = inputs.GetTypeByMetadataName("Sample.Widget")!.ContainingAssembly.Identity;
                var runtimeReferenceImage = CreateExternalWidgetImage(externalName);
                var fieldType = ReferencedWidgetType();
                var body = new TransferOnlyOpaqueTypeOfExpression(independentNamespaceUse);
                var owner = new PreparedNameTransferOwner(fieldType, body);
                owner.EnsureBuilt();
                FinalizeGeneratedInstanceOwner(owner);
                Assert.That(services.TypeFactory.CSharpTypeMap, Is.Empty);
                Assert.That(owner.Fields, Has.Count.EqualTo(1));
                Assert.That(owner.Methods, Has.Count.EqualTo(1));
                Assert.That(owner.Constructors, Is.Empty);
                Assert.That(owner.Properties, Is.Empty);
                Assert.That(owner.NestedTypes, Is.Empty);
                Assert.That(owner.BaseType, Is.Null);
                Assert.That(owner.DeclaringTypeProvider, Is.Null);
                Assert.That(ReferenceEquals(owner.Fields[0].Type, fieldType), Is.True);

                using var prepared = PreparedFieldTypes.Create(new TypeProvider[] { owner }, inputs, _ => true);
                Assert.That(body.Calls, Is.Zero, "Preparation must never execute opaque IR.");
                Assert.That(services.WriteCallbacks, Is.Empty, "Preparation must not obtain a writer.");
                Assert.That(prepared.CanWriteSimpleName(owner, owner.Fields[0]), Is.True,
                    "Independent legacy FIELD proof must be positive before writing.");
                Assert.That(body.Calls, Is.Zero);

                // Exactly one factory call and one actual default TypeProviderWriter pass.
                var writer = services.GetWriter(owner);
                Assert.That(writer.GetType(), Is.EqualTo(typeof(TypeProviderWriter)));
                writer.PreparedFieldTypes = prepared;
                var output = writer.Write();
                Assert.That(body.Calls, Is.EqualTo(1));
                Assert.That(services.WriteCallbacks, Has.Count.EqualTo(1));
                Assert.That(services.WriteCallbacks[owner], Is.EqualTo(1));
                Assert.That(prepared.CanCommitBodyNames(output), Is.False,
                    "A test-only output append without an actual consumed permission must not license production body commit.");

                // Save the ORIGINAL staged file. Never select again on a terminal result.
                var original = output.Content;
                var qualified = output.QualifiedContent;
                Assert.That(qualified, Is.Not.Null);
                var legacyWithoutPreparedNames = output.WithoutPreparedNames().Content;
                Assert.That(legacyWithoutPreparedNames, Is.EqualTo(qualified));
                StringAssert.Contains("// <auto-generated/>", original);
                StringAssert.Contains("using System;", original);
                var shortTree = CSharpSyntaxTree.ParseText(original);
                var shortRoot = shortTree.GetRoot();
                var shortField = shortRoot.DescendantNodes().OfType<FieldDeclarationSyntax>().Single();
                var shortMethod = shortRoot.DescendantNodes().OfType<MethodDeclarationSyntax>().Single();
                var shortTypeOf = shortRoot.DescendantNodes().OfType<TypeOfExpressionSyntax>().Single();
                Assert.That(shortField.Declaration.Type.ToString(), Is.EqualTo("Widget"));
                Assert.That(shortTypeOf.Type.ToString(), Is.EqualTo("Exception"));
                Assert.That(shortMethod.Identifier.ValueText, Is.EqualTo("M"));
                Assert.That(shortMethod.ExpressionBody, Is.Not.Null);
                Assert.That(shortMethod.Body, Is.Null);
                Assert.That(shortField.Declaration.Type.Span.End, Is.LessThan(shortTypeOf.Type.SpanStart));

                // Independent byte oracle: change only the two syntax-identified type
                // spans in the short ORIGINAL. Header/imports/docs/trivia stay exact.
                // No text search, reducer, workspace, formatter, or second writer.
                string ExpectedBytes(bool fieldAllowed, bool bodyAllowed)
                {
                    var expected = original;
                    if (!bodyAllowed)
                    {
                        expected = expected.Remove(shortTypeOf.Type.SpanStart, shortTypeOf.Type.Span.Length)
                            .Insert(shortTypeOf.Type.SpanStart, "global::System.Exception");
                    }
                    if (!fieldAllowed)
                    {
                        expected = expected.Remove(shortField.Declaration.Type.SpanStart, shortField.Declaration.Type.Span.Length)
                            .Insert(shortField.Declaration.Type.SpanStart, "global::Sample.Widget");
                    }
                    return expected;
                }
                Assert.That(qualified, Is.EqualTo(ExpectedBytes(false, false)));

                string[]? baselineDiagnostics = null;
                foreach (var (fieldAllowed, bodyAllowed) in new[]
                {
                    (true, true), (true, false), (false, true), (false, false)
                })
                {
                    var selected = output.SelectPreparedNames(fieldAllowed, bodyAllowed);
                    Assert.That(selected.Content, Is.EqualTo(ExpectedBytes(fieldAllowed, bodyAllowed)),
                        $"Exact bytes for field={fieldAllowed}, body={bodyAllowed}");
                    Assert.That(selected.Name, Is.EqualTo(output.Name));
                    if (fieldAllowed && bodyAllowed)
                    {
                        Assert.That(selected, Is.SameAs(output));
                    }
                    if (!fieldAllowed && !bodyAllowed)
                    {
                        Assert.That(selected.Content, Is.EqualTo(qualified));
                        Assert.That(selected.Content, Is.EqualTo(legacyWithoutPreparedNames));
                    }

                    var tree = CSharpSyntaxTree.ParseText(selected.Content);
                    var compilation = inputs.WithAssemblyName("PreparedNameTransfer_" + Guid.NewGuid().ToString("N"))
                        .AddSyntaxTrees(tree);
                    var diagnostics = compilation.GetDiagnostics();
                    Assert.That(diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error), Is.Empty,
                        string.Join("\n", diagnostics));
                    // Namespace use is a separate policy concern, not a rendering
                    // permission. Preserve the observed hidden-only delta exactly.
                    // The independent Type use additionally requires full parity.
                    var unusedImports = diagnostics.Where(d => d.Id == "CS8019").ToArray();
                    Assert.That(unusedImports, Has.Length.EqualTo(!independentNamespaceUse && !bodyAllowed ? 1 : 0));
                    Assert.That(unusedImports.All(d => d.Severity == DiagnosticSeverity.Hidden), Is.True);
                    var diagnosticSummary = diagnostics.Where(d => d.Id != "CS8019")
                        .Select(d => $"{d.Severity}:{d.Id}:{d.GetMessage()}")
                        .OrderBy(d => d, StringComparer.Ordinal).ToArray();
                    baselineDiagnostics ??= diagnosticSummary;
                    Assert.That(diagnosticSummary, Is.EqualTo(baselineDiagnostics));
                    var root = tree.GetRoot();
                    var fieldSyntax = root.DescendantNodes().OfType<FieldDeclarationSyntax>().Single();
                    var typeOfSyntax = root.DescendantNodes().OfType<TypeOfExpressionSyntax>().Single();
                    Assert.That(fieldSyntax.Declaration.Type.ToString(),
                        Is.EqualTo(fieldAllowed ? "Widget" : "global::Sample.Widget"));
                    Assert.That(typeOfSyntax.Type.ToString(),
                        Is.EqualTo(bodyAllowed ? "Exception" : "global::System.Exception"));
                    var model = compilation.GetSemanticModel(tree);
                    if (independentNamespaceUse)
                    {
                        var witness = root.DescendantNodes().OfType<DefaultExpressionSyntax>().Single();
                        Assert.That(witness.Type.ToString(), Is.EqualTo("Type"));
                        Assert.That(SymbolEqualityComparer.Default.Equals(model.GetTypeInfo(witness.Type).Type,
                            compilation.GetTypeByMetadataName("System.Type")), Is.True);
                    }
                    var field = (IFieldSymbol)model.GetDeclaredSymbol(fieldSyntax.Declaration.Variables.Single())!;
                    Assert.That(field.Name, Is.EqualTo("_value"));
                    Assert.That(field.ContainingType.ToDisplayString(), Is.EqualTo("Sample.Clock"));
                    Assert.That(field.Type.ToDisplayString(), Is.EqualTo("Sample.Widget"));
                    Assert.That(field.Type.ContainingAssembly.Identity, Is.EqualTo(externalIdentity));
                    Assert.That(field.Type.ContainingAssembly.Name, Is.EqualTo(externalName));
                    var typeOf = (ITypeOfOperation)model.GetOperation(typeOfSyntax)!;
                    Assert.That(SymbolEqualityComparer.Default.Equals(typeOf.TypeOperand,
                        compilation.GetTypeByMetadataName("System.Exception")), Is.True);
                    Assert.That(SymbolEqualityComparer.Default.Equals(typeOf.Type,
                        compilation.GetTypeByMetadataName("System.Type")), Is.True);

                    using var image = new MemoryStream();
                    var emit = compilation.Emit(image);
                    Assert.That(emit.Success, Is.True, string.Join("\n", emit.Diagnostics));
                    var context = new AssemblyLoadContext("PreparedNameTransfer_" + Guid.NewGuid().ToString("N"), isCollectible: true);
                    try
                    {
                        using var referenceStream = new MemoryStream(runtimeReferenceImage);
                        context.LoadFromStream(referenceStream);
                        image.Position = 0;
                        var assembly = context.LoadFromStream(image);
                        var clock = assembly.GetType("Sample.Clock", throwOnError: true)!;
                        var method = clock.GetMethod("M", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)!;
                        Assert.That(method.ReturnType, Is.EqualTo(typeof(Type)));
                        Assert.That(method.Invoke(null, null), Is.EqualTo(typeof(Exception)));
                    }
                    finally { context.Unload(); }

                    Assert.That(output.Content, Is.EqualTo(original));
                    Assert.That(output.QualifiedContent, Is.EqualTo(qualified));
                    Assert.That(body.Calls, Is.EqualTo(1), "Selections/compiler/emit/runtime must not replay opaque IR.");
                    Assert.That(services.WriteCallbacks, Has.Count.EqualTo(1));
                    Assert.That(services.WriteCallbacks[owner], Is.EqualTo(1));
                }
                Assert.That(body.Calls, Is.EqualTo(1));
                Assert.That(services.WriteCallbacks[owner], Is.EqualTo(1));
            }
            finally { CodeModelGenerator.Instance = previous; }
        }

        private sealed class PreparedNameTransferOwner(CSharpType fieldType, ValueExpression body) : TypeProvider
        {
            protected override string BuildName() => "Clock";
            protected override string BuildNamespace() => "Sample";
            protected override string BuildRelativeFilePath() => "PreparedNameTransfer.Clock.cs";
            protected override TypeSignatureModifiers BuildDeclarationModifiers() => TypeSignatureModifiers.Internal | TypeSignatureModifiers.Class;
            protected internal override FieldProvider[] BuildFields() =>
                [new FieldProvider(FieldModifiers.Private, fieldType, "_value", this)];
            protected internal override MethodProvider[] BuildMethods() =>
                [new MethodProvider(new MethodSignature("M", null,
                    MethodSignatureModifiers.Public | MethodSignatureModifiers.Static, typeof(Type), null, []), body, this)];
        }

        // TEST ONLY, deliberately opaque. This is not a facts/permission producer.
        private sealed record TransferOnlyOpaqueTypeOfExpression(bool IndependentNamespaceUse) : ValueExpression
        {
            internal int Calls { get; private set; }
            internal override void WriteCore(CodeWriter writer)
            {
                Calls++;
                writer.UseNamespace("System");
                if (IndependentNamespaceUse) { writer.AppendRaw("default(Type) ?? "); }
                writer.AppendRaw("typeof(");
                Assert.That(writer.TryAppendPreparedBodyName("Exception", "global::System.Exception"), NUnit.Framework.Is.True);
                writer.AppendRaw(")");
            }
        }
    }
